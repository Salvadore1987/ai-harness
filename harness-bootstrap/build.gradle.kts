    alias(libs.plugins.spring.boot)
    alias(libs.plugins.graalvm.native)
    id("org.springframework.boot.aot")
}

dependencies {
    implementation(project(":harness-infrastructure"))
    implementation(project(":harness-adapter-ollama"))
    implementation(libs.spring.boot.starter)
    implementation(libs.spring.boot.starter.log4j2)
    // Constraint annotations of HarnessProperties records read while compiling BeanConfig.
    implementation(libs.spring.boot.starter.validation)

    testImplementation(testFixtures(project(":harness-application")))
    testImplementation(testFixtures(project(":harness-infrastructure")))
    testImplementation(libs.spring.boot.starter.test)
    testImplementation(libs.archunit.junit5)
    testImplementation(libs.picocli)
    testImplementation(libs.mapstruct)
    testImplementation(libs.wiremock.standalone)
}

tasks.bootJar {
    archiveFileName.set("harness.jar")
}

graalvmNative {
    binaries.named("main") {
        imageName.set("harness")
        mainClass.set("dev.localllm.harness.bootstrap.HarnessApplication")
        // Spring AOT output: bean definitions and runtime hints generated by processAot.
        classpath(sourceSets.getByName("aot").runtimeClasspath)
        // JLine reaches the terminal through FFM.
        buildArgs.add("--enable-native-access=ALL-UNNAMED")
        javaLauncher.set(javaToolchains.launcherFor {
            languageVersion.set(JavaLanguageVersion.of(libs.versions.jdk.get()))
            nativeImageCapable.set(true)
        })
    }
}

// Code generated by Spring AOT is not ours to lint.
tasks.matching { task ->
    task.name in setOf("checkstyleAot", "checkstyleAotTest", "pmdAot", "pmdAotTest",
        "spotbugsAot", "spotbugsAotTest")
}.configureEach {
    enabled = false
}

val nativeBinary = layout.buildDirectory.file("native/nativeCompile/harness")

tasks.test {
    systemProperty("harness.native.binary", nativeBinary.get().asFile.absolutePath)
    if (providers.gradleProperty("includeTags").orNull?.contains("native") == true) {
        dependsOn(tasks.named("nativeCompile"))
    }
}

// The plain jar puts the bootstrap classes on the native-image classpath.
tasks.jar {
    archiveClassifier.set("plain")
}

val coveredProjects = listOf(
    project(":harness-application"),
    project(":harness-infrastructure"),
    project(":harness-adapter-ollama"),
    project
)

val overallCoverageVerification by tasks.registering(JacocoCoverageVerification::class) {
    description = "Verifies the overall line coverage threshold (60 %) across all modules."
    coveredProjects.forEach { dependsOn(it.tasks.named("test")) }
    executionData.setFrom(coveredProjects.map { fileTree(it.layout.buildDirectory) { include("jacoco/*.exec") } })
    sourceDirectories.setFrom(coveredProjects.map { it.file("src/main/java") })
    classDirectories.setFrom(coveredProjects.map {
        fileTree(it.layout.buildDirectory.dir("classes/java/main")) { exclude("**/*MapperImpl.class") }
    })
    violationRules {
        rule {
            limit {
                minimum = "0.60".toBigDecimal()
            }
        }
    }
}

tasks.jacocoTestCoverageVerification {
    enabled = false
}

tasks.check {
    dependsOn(overallCoverageVerification)
}
